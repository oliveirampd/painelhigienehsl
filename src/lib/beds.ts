/** Andar deduzido do número do leito (ex: 1858 -> 18, 859 -> 8, 601 -> 6). */
export function bedFloor(n: string): number {
  return n.length >= 4 ? parseInt(n.slice(0, 2), 10) : parseInt(n.slice(0, 1), 10);
}
